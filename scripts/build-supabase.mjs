// Bundles server/edge.ts into the single file Supabase runs as the "kazi" Edge Function.
import { readFileSync } from 'node:fs';
import { build } from 'esbuild';

// The Anthropic SDK isn't bundled: Supabase's Deno runtime loads it from npm, at the exact version this project uses.
const sdkVersion = JSON.parse(readFileSync('package.json', 'utf8')).dependencies['@anthropic-ai/sdk'];
const npmImports = {
  name: 'npm-imports',
  setup(b) {
    b.onResolve({ filter: /^@anthropic-ai\/sdk(\/.*)?$/ }, (args) => ({
      path: args.path.replace('@anthropic-ai/sdk', `npm:@anthropic-ai/sdk@${sdkVersion}`),
      external: true,
    }));
  },
};

await build({
  entryPoints: ['server/edge.ts'],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  plugins: [npmImports],
  target: 'es2022',
  legalComments: 'none',
  outfile: 'supabase/functions/kazi/index.ts',
  banner: {
    js: [
      '// @ts-nocheck',
      '// Kazikwanza Edge Function for Supabase.',
      '// GENERATED by `npm run build:supabase` from server/edge.ts and server/core.ts; do not edit by hand.',
      '// To deploy without the CLI: Supabase > Edge Functions > Deploy a new function > Via editor,',
      '// name it "kazi", paste this whole file, turn off "Verify JWT", and deploy.',
      '// For Claude checks, add the secret ANTHROPIC_API_KEY under Edge Functions > Secrets.',
      '',
    ].join('\n'),
  },
});
